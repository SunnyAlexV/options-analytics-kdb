"""Which smile rule describes BTC options best? Measure it on recorded data (Phase 5).

    python scripts/eval_smile_rules.py --recording ~/kdbdata/raw               # replay a feed recording
    python scripts/eval_smile_rules.py --gw 5013 --start 2026.10.09 --end 2026.10.10   # smiles in kdb+
    python scripts/eval_smile_rules.py --recording ~/kdbdata/raw --report       # also write the results file

Method (risk/dynamics.py): standard points on each smile (call deltas 10..90); for each
interval, the observed change in vol at fixed strike vs what each rule predicts from the
forward move alone, and each option's P&L after hedging with that rule's delta.
R is estimated on one half of the intervals and scored on the other, both ways round.

Decision rule, fixed before looking at the data: pooled tenors, 5-minute horizon,
hedged-P&L RMSE; a rule must win on both folds, otherwise the better of sticky-strike /
sticky-moneyness on average is kept. The result is what RISK_R in config.env should be.
"""
import argparse
import os
import pickle
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from risk.dynamics import decide, evaluate_rules, print_results  # noqa: E402

HORIZONS = (60, 300, 900)


def from_recording(folder, cache=None):
    """Replay the recording through the surface engine; collect every published smile."""
    if cache and Path(cache).exists():
        return pickle.load(open(cache, "rb"))
    from engine.replay import load_recording, replay
    data = load_recording(folder)
    rows = []
    replay(data, on_output=lambda now, ivs, fw, sf, eng: rows.extend(dict(r, now=now) for r in sf))
    if cache:
        pickle.dump(rows, open(cache, "wb"))
    return rows


def from_gateway(port, start, end):
    """Smiles the live engine published, read back from kdb+ (time = publication time)."""
    os.environ.setdefault("PYKX_UNLICENSED", "true")
    import pykx as kx
    from engine.ipc import records
    with kx.SyncQConnection(port=port, no_ctx=True) as c:
        t = c(f"{{update now:`long$(`timestamp$date)+`long$time from .gw.get[`surface;{start};{end};`]}}", None)
        rows = records(t)
    return sorted(rows, key=lambda r: r["now"])


def report(path, results, decision, src, span_h, n_rows):
    lines = ["# Phase 5: which smile rule fits BTC options?", "",
             f"Data: {src}, {span_h:.1f} hours, {n_rows:,} published smiles. "
             f"Generated by `scripts/eval_smile_rules.py` on {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())}.",
             "",
             "Rule family: after a log forward move x, sigma_new(K) = sigma_old(ln(K/F) - (1 - R) x). "
             "R = 1 sticky-strike, R = 0 sticky-moneyness. Scores are out of sample: R is estimated on one half "
             "of the intervals and scored on the other, both ways round (A->B, B->A).", "",
             "Decision rule (fixed before the data was seen): pooled tenors, 5-minute horizon, hedged-P&L RMSE; "
             "a rule must win on both folds, otherwise the better named rule on average is kept.", "",
             f"**Decision: R = {decision['R']:g}** ({decision.get('rule', '')}: {decision['why']}).", "",
             "| horizon | tenor | fold | R_hat ± se | vol RMSE R=0 | R=1 | R_hat | hedged RMSE (bp) R=0 | R=1 | R_hat |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for r in results:
        s0, s1, se = (r.scores[k] for k in ("sticky-moneyness (R=0)", "sticky-strike (R=1)", "estimated"))
        lines.append(f"| {r.horizon_s:.0f} s | {r.tenor} | {r.fold} | {r.R_hat:+.2f} ± {r.R_se:.2f} | "
                     f"{s0['vol_rmse']:.4f} | {s1['vol_rmse']:.4f} | {se['vol_rmse']:.4f} | "
                     f"{s0['hedge_rmse_bp']:.3f} | {s1['hedge_rmse_bp']:.3f} | {se['hedge_rmse_bp']:.3f} |")
    Path(path).write_text("\n".join(lines) + "\n")
    print(f"\nWrote {path}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--recording", help="feed recording folder (python -m feed --record)")
    ap.add_argument("--cache", help="pickle file to cache the replayed smiles")
    ap.add_argument("--gw", type=int, help="gateway port")
    ap.add_argument("--start", help="first date for --gw, YYYY.MM.DD")
    ap.add_argument("--end", help="last date for --gw, YYYY.MM.DD")
    ap.add_argument("--report", action="store_true", help="write results/phase5_smile_rules.md")
    args = ap.parse_args()

    if args.recording:
        rows, src = from_recording(args.recording, args.cache), f"feed recording {args.recording}"
    else:
        rows, src = from_gateway(args.gw, args.start, args.end or args.start), f"kdb+ {args.start}..{args.end}"
    span_h = (rows[-1]["now"] - rows[0]["now"]) / 3.6e12
    print(f"{len(rows):,} smiles over {span_h:.1f} hours")
    results = evaluate_rules(rows, HORIZONS)
    print_results(results)
    d = decide(results)
    print(f"\nDecision (pooled, 5-minute horizon, hedged P&L, must win both folds): R = {d['R']:g} -- "
          f"{d.get('rule', '')}: {d['why']}")
    if args.report:
        report(ROOT / "results" / "phase5_smile_rules.md", results, d, src, span_h, len(rows))


if __name__ == "__main__":
    main()
